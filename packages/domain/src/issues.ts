export interface SubmitReportInput {
  blockId: string;
  spotId: string;
  selectedCategoryId: string;
  title: string;
  description?: string | undefined;
  capturedAt?: string | undefined;
  latitude?: number | undefined;
  longitude?: number | undefined;
  reportingContext?: Record<string, unknown> | undefined;
  /** Set by the route after the photo was validated and stored. */
  evidenceStorageKey?: string | null | undefined;
}

export interface SubmitReportResult {
  reportId: string;
  issueId: string;
  issuePublicReference: string;
  /** False when this submission was recognised as a duplicate of an open issue. */
  createdNewIssue: boolean;
  duplicateMatchStatus: 'LINKED' | 'NOT_CHECKED';
}

/**
 * Creates a report and its master issue atomically.
 *
 * DUPLICATE SAFETY (the centrepiece of Phase 1):
 *   - dedupe_key is deterministic (spot + category by default).
 *   - `createOrFindDuplicate` uses INSERT ... ON CONFLICT DO NOTHING RETURNING.
 *   - Two simultaneous submissions therefore yield ONE master ticket, and the
 *     losing request links to the winner instead of creating a second ticket.
 *   - Both reports remain individually traceable (each earns its own tokens later),
 *     which is exactly what the brief requires.
 *
 * NOTE ON EVIDENCE: the photo is written to storage BEFORE this transaction begins.
 * Keeping file I/O out of the database transaction avoids holding row locks during a
 * slow disk write. A failed transaction can leave an orphaned file, which is
 * harmless (unreferenced, unreadable without authorization) but is a known
 * limitation to sweep in Phase 2.
 */
export async function submitReport(db: Db, actor: Actor, input: SubmitReportInput): Promise<SubmitReportResult> {
  return db.withTransaction(async (tx) => {
    // 1. Location must exist IN THIS WORKSPACE. This single check covers both
    //    "nonexistent block/spot" and "spot belonging to another workspace".
    const spot = await campusRepo.resolveSpot(tx, actor.workspaceId, input.spotId);
    if (!spot) {
      throw validationFailed('The selected campus spot does not exist in your campus.');
    }
    if (spot.block_id !== input.blockId) {
      throw validationFailed('The selected spot does not belong to the selected block.');
    }
    if (!spot.active || !spot.block_active) {
      throw validationFailed('The selected campus location is no longer accepting reports.');
    }

    // 2. Category must be a real, active, configurable category.
    const categoryOk = await campusRepo.categoryExists(tx, input.selectedCategoryId);
    if (!categoryOk) throw validationFailed('The selected issue category is not valid.');

    // 3. Durably record the submission. captured_at is stored as UNTRUSTED evidence;
    //    submitted_at is generated by the server and is authoritative.
    const report = await reportRepo.create(tx, {
      workspaceId: actor.workspaceId,
      reporterUserId: actor.userId,
      blockId: input.blockId,
      spotId: input.spotId,
      selectedCategoryId: input.selectedCategoryId,
      capturedAt: input.capturedAt ?? null,
      latitude: input.latitude ?? null,
      longitude: input.longitude ?? null,
      reportingContext: input.reportingContext,
      evidenceStorageKey: input.evidenceStorageKey ?? null,
    });

    await outboxPublisher.publish(tx, {
      eventType: 'report.created',
      workspaceId: actor.workspaceId,
      workspace: actor.workspaceKind,
      entityType: 'REPORT',
      entityId: report.id,
      entityVersion: 1,
      actorUserId: actor.userId,
      payload: {
        reportId: report.id,
        blockId: input.blockId,
        spotId: input.spotId,
        categoryId: input.selectedCategoryId,
        hasEvidence: Boolean(input.evidenceStorageKey),
      },
    });

    // 4. Create or find the master repair ticket (concurrency-safe by construction).
    const granularity = await getDedupeGranularity(tx);
    const dedupeKey = computeDedupeKey({
      blockId: input.blockId,
      spotId: input.spotId,
      categoryId: input.selectedCategoryId,
      granularity,
    });

    // The overdue threshold is CONFIGURED, not hardcoded.
    const overdueHours = await getOverdueHours(tx);
    const dueAt = new Date(Date.now() + overdueHours * 60 * 60 * 1000);

    const publicReference = await issueRepo.nextPublicReference(tx, actor.workspaceId, new Date().getUTCFullYear());

    const { issue, created } = await issueRepo.createOrFindDuplicate(tx, {
      workspaceId: actor.workspaceId,
      publicReference,
      title: input.title,
      description: input.description ?? null,
      categoryId: input.selectedCategoryId,
      severity: null, // severity is an AI/human assessment, never a client claim
      blockId: input.blockId,
      spotId: input.spotId,
      createdByUserId: actor.userId,
      dueAt,
      dedupeKey,
    });

    // 5. Link the report to its master ticket.
    await reportRepo.applyValidationOutcome(tx, actor.workspaceId, report.id, {
      validationStatus: 'PENDING',
      duplicateMatchStatus: created ? 'NOT_CHECKED' : 'LINKED',
    });
    await reportRepo.linkToIssue(tx, actor.workspaceId, report.id, issue.id);

    if (created) {
      // Opening state recorded in history, transactionally, like every other transition.
      await issueRepo.recordStatusHistory(tx, {
        workspaceId: actor.workspaceId,
        issueId: issue.id,
        previousStatus: null,
        newStatus: 'SUBMITTED',
        changedByUserId: actor.userId,
        reason: 'Issue opened from student report',
      });

      await outboxPublisher.publish(tx, {
        eventType: 'issue.created',
        workspaceId: actor.workspaceId,
        workspace: actor.workspaceKind,
        entityType: 'ISSUE',
        entityId: issue.id,
        entityVersion: issue.version,
        actorUserId: actor.userId,
        payload: {
          issueId: issue.id,
          publicReference: issue.public_reference,
          reportId: report.id,
          status: 'SUBMITTED',
          blockId: issue.block_id,
          spotId: issue.spot_id,
          categoryId: issue.category_id,
          dueAt: new Date(dueAt).toISOString(),
        },
      });
    } else {
      await outboxPublisher.publish(tx, {
        eventType: 'issue.duplicate_linked',
        workspaceId: actor.workspaceId,
        workspace: actor.workspaceKind,
        entityType: 'ISSUE',
        entityId: issue.id,
        entityVersion: issue.version,
        actorUserId: actor.userId,
        payload: {
          issueId: issue.id,
          reportId: report.id,
          publicReference: issue.public_reference,
          reportCount: Number(issue.report_count ?? 0),
        },
      });
    }

    return {
      reportId: report.id,
      issueId: issue.id,
      issuePublicReference: issue.public_reference,
      createdNewIssue: created,
      duplicateMatchStatus: created ? 'NOT_CHECKED' : 'LINKED',
    };
  });
}

async function getDedupeGranularity(tx: Tx): Promise<DedupeGranularity> {
  const r = await tx.query<{ value: unknown }>(
    `SELECT value FROM app_settings WHERE key = 'dedupe_granularity'`,
  );
  if (r.rows.length === 0) return 'spot_category';
  const raw = r.rows[0]!.value;
  const value = typeof raw === 'string' ? JSON.parse(raw) : raw;
  return value === 'block_category' ? 'block_category' : 'spot_category';
}

