/**
 * Issue + report workflow service. ALL business rules for the lifecycle live here.
 *
 * Route handlers are intentionally thin: validate input -> call one of these
 * functions -> map the result. No route handler contains a status check, a token
 * amount, or an authorization rule of its own. That is what stops the mobile app and
 * the admin website from drifting into competing implementations (brief Section 6).
 *
 * Every mutation runs inside a single database transaction that also writes the
 * status history, the audit row and the outbox event. Either all of it commits or
 * none of it does — a client can never be told "success" for a write that failed.
 */
import {
  TOKEN_POLICY,
  tokenCreditIdempotencyKey,
  type IssueStatus,
  type Role,
  type Severity,
} from '@campus/contracts';
import {
  audit as auditRepo,
  campus as campusRepo,
  getOverdueHours,
  getTokensPerValidatedReport,
  issues as issueRepo,
  reports as reportRepo,
  type Db,
  type Tx,
} from '@campus/db';
import { assertCanClaim, assertCanOperate, assertTransition } from './state-machine.js';
import { computeDedupeKey, type DedupeGranularity } from './dedupe.js';
import { awardForValidatedReport, isTokenEligible } from './tokens.js';
import { alreadyClaimed, forbidden, notFound, validationFailed, workspaceViolation } from './errors.js';
