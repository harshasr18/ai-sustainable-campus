/**
 * Claims an issue for an HOD/ADMIN.
 *
 * Concurrency: `lockForUpdate` serialises competing claims, and the UPDATE is
 * additionally guarded by the version we read under that lock. Two HODs tapping
 * "Claim" simultaneously therefore produce one success and one ALREADY_CLAIMED —
 * never two owners.
 */
export async function claimIssue(
  db: Db,
  actor: Actor,
  input: { issueId: string; expectedVersion?: number | undefined },
): Promise<{ issue: ReturnType<typeof toIssueDto> }> {
  assertCanClaim(actor.role);

  return db.withTransaction(async (tx) => {
    const current = await issueRepo.lockForUpdate(tx, actor.workspaceId, input.issueId);
    if (!current) throw notFound('Issue not found in your campus.');
    if (current.status === 'RESOLVED') throw alreadyClaimed('This issue is already resolved.');

    const result = await issueRepo.claim(tx, actor.workspaceId, input.issueId, actor.userId, input.expectedVersion);
    if (!result.ok) {
      if (result.reason === 'NOT_FOUND') throw notFound('Issue not found in your campus.');
      if (result.reason === 'ALREADY_CLAIMED') throw alreadyClaimed();
      throw alreadyClaimed('This issue was modified by someone else. Refresh and try again.');
    }

    await auditRepo.record(tx, {
      workspaceId: actor.workspaceId,
      actorUserId: actor.userId,
      action: 'issue.claimed',
      entityType: 'ISSUE',
      entityId: input.issueId,
      before: { claimedByUserId: current.claimed_by_user_id },
      after: { claimedByUserId: actor.userId },
    });

    await outboxPublisher.publish(tx, {
      eventType: 'issue.claimed',
      workspaceId: actor.workspaceId,
      workspace: actor.workspaceKind,
      entityType: 'ISSUE',
      entityId: input.issueId,
      entityVersion: result.issue.version,
      actorUserId: actor.userId,
      payload: { issueId: input.issueId, claimedByUserId: actor.userId, status: result.issue.status },
    });

    return { issue: toIssueDto(result.issue) };
  });
}

export type TransitionTarget = Extract<IssueStatus, 'APPROVED' | 'IN_PROGRESS' | 'RESOLVED'>;

/**
 * The ONLY way an issue changes status.
 *
 * There is no generic "update issue" endpoint and no PATCH that accepts a status
 * field — the brief forbids it ("Do not silently permit arbitrary status updates").
 * The domain state machine decides legality and permission; this function then
 * persists status + history + audit + event in one transaction.
 */
export async function transitionIssue(
  db: Db,
  actor: Actor,
  input: { issueId: string; to: TransitionTarget; reason?: string | undefined; resolutionNote?: string | undefined },
): Promise<{ issue: ReturnType<typeof toIssueDto> }> {
  return db.withTransaction(async (tx) => {
    // Lock FIRST: serialises competing transitions on the same issue.
    const current = await issueRepo.lockForUpdate(tx, actor.workspaceId, input.issueId);
    if (!current) throw notFound('Issue not found in your campus.');

    if (input.to === 'RESOLVED' && !(input.resolutionNote ?? '').trim()) {
      // Explicit, specific error for the most common client mistake.
      throw validationFailed('A completion note is required to resolve an issue.');
    }

    // Throws FORBIDDEN (role) or INVALID_STATE_TRANSITION (illegal move).
    assertTransition({
      from: current.status,
      to: input.to,
      role: actor.role,
      resolutionNote: input.resolutionNote ?? null,
    });

    const updated = await issueRepo.applyTransition(
      tx,
      actor.workspaceId,
      input.issueId,
      input.to,
      input.to === 'RESOLVED' ? (input.resolutionNote ?? null) : null,
    );

    // Brief 7F: "Every successful status transition must be recorded transactionally."
    await issueRepo.recordStatusHistory(tx, {
      workspaceId: actor.workspaceId,
      issueId: input.issueId,
      previousStatus: current.status,
      newStatus: input.to,
      changedByUserId: actor.userId,
      reason: input.reason ?? null,
    });

    await auditRepo.record(tx, {
      workspaceId: actor.workspaceId,
      actorUserId: actor.userId,
      action: 'issue.status_changed',
      entityType: 'ISSUE',
      entityId: input.issueId,
      before: { status: current.status },
      after: { status: input.to },
      reason: input.reason ?? null,
    });

    await outboxPublisher.publish(tx, {
      eventType: 'issue.status_changed',
      workspaceId: actor.workspaceId,
      workspace: actor.workspaceKind,
      entityType: 'ISSUE',
      entityId: input.issueId,
      entityVersion: updated.version,
      actorUserId: actor.userId,
      payload: { issueId: input.issueId, previousStatus: current.status, newStatus: input.to, reason: input.reason ?? null },
    });

    if (input.to === 'RESOLVED') {
      await outboxPublisher.publish(tx, {
        eventType: 'issue.resolved',
        workspaceId: actor.workspaceId,
        workspace: actor.workspaceKind,
        entityType: 'ISSUE',
        entityId: input.issueId,
        entityVersion: updated.version,
        actorUserId: actor.userId,
        payload: {
          issueId: input.issueId,
          publicReference: updated.public_reference,
          resolutionNote: updated.resolution_note,
          resolvedAt: new Date(updated.resolved_at as string).toISOString(),
        },
      });
    }

    return { issue: toIssueDto(updated) };
  });
}

