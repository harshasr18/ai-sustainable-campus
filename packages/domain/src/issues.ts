/**
 * Records the server-side verdict on a report and awards tokens if — and only if —
 * the verdict makes it eligible. This is the seam the Phase 2 AI pipeline plugs into.
 *
 * Called by trusted server code only (staff review endpoint now; AI worker later).
 * There is NO HTTP route that lets a client pick its own validation status.
 */
export async function recordValidationOutcome(
  db: Db,
  actor: Actor,
  input: {
    reportId: string;
    validationStatus: 'AI_VALIDATED' | 'HUMAN_VALIDATED' | 'DUPLICATE_VALIDATED' | 'REJECTED';
    duplicateMatchStatus?: 'NO_MATCH' | 'LINKED' | 'CANDIDATE_FOUND' | 'HUMAN_OVERRIDDEN';
    aiPredictedCategoryId?: string | null;
    aiConfidence?: number | null;
    aiSeverity?: string | null;
    repairRecommendation?: string | null;
    reason?: string;
  },
): Promise<{ reportId: string; tokensAwarded: number; alreadyAwarded: boolean; tokenEligible: boolean }> {
  return db.withTransaction(async (tx) => {
    const report = await reportRepo.findById(tx, actor.workspaceId, input.reportId);
    if (!report) throw notFound('Report not found in your campus.');

    const updated = await reportRepo.applyValidationOutcome(tx, actor.workspaceId, input.reportId, {
      validationStatus: input.validationStatus,
      duplicateMatchStatus: input.duplicateMatchStatus ?? null,
      aiPredictedCategoryId: input.aiPredictedCategoryId ?? null,
      aiConfidence: input.aiConfidence ?? null,
      aiSeverity: input.aiSeverity ?? null,
      repairRecommendation: input.repairRecommendation ?? null,
    });
    if (!updated) throw notFound('Report not found in your campus.');

    await outboxPublisher.publish(tx, {
      eventType: 'report.validated',
      workspaceId: actor.workspaceId,
      workspace: actor.workspaceKind,
      entityType: 'REPORT',
      entityId: input.reportId,
      entityVersion: 1,
      actorUserId: actor.userId,
      payload: {
        reportId: input.reportId,
        validationStatus: input.validationStatus,
        duplicateMatchStatus: updated.duplicate_match_status,
        issueId: updated.issue_id,
      },
    });

    await auditRepo.record(tx, {
      workspaceId: actor.workspaceId,
      actorUserId: actor.userId,
      action: 'report.validation_recorded',
      entityType: 'REPORT',
      entityId: input.reportId,
      before: { validationStatus: report.validation_status },
      after: { validationStatus: input.validationStatus },
      reason: input.reason ?? null,
    });

    const eligible = isTokenEligible(input.validationStatus);
    if (!eligible) {
      return { reportId: input.reportId, tokensAwarded: 0, alreadyAwarded: false, tokenEligible: false };
    }

    // Reward amount comes from configuration, not a literal in this file.
    const amount = await getTokensPerValidatedReport(tx);

    // Idempotent: a retry (or a replayed queue message) cannot double-award.
    const award = await awardForValidatedReport(tx, {
      workspaceId: actor.workspaceId,
      userId: report.reporter_user_id,
      reportId: input.reportId,
      validationStatus: input.validationStatus,
      amount,
    });

    if (award.inserted) {
      await outboxPublisher.publish(tx, {
        eventType: 'token.credited',
        workspaceId: actor.workspaceId,
        workspace: actor.workspaceKind,
        entityType: 'TOKEN_TRANSACTION',
        entityId: award.transactionId!,
        entityVersion: 1,
        actorUserId: null,
        payload: {
          userId: report.reporter_user_id,
          reportId: input.reportId,
          amount: award.amount,
          idempotencyKey: tokenCreditIdempotencyKey(input.reportId),
        },
      });
    }

    return {
      reportId: input.reportId,
      tokensAwarded: awardedOrExisting(award.inserted, award.amount),
      alreadyAwarded: !award.inserted,
      tokenEligible: true,
    };
  });
}

const awardedOrExisting = (inserted: boolean, amount: number) => (inserted ? amount : 0);

