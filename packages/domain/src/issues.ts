export async function getIssue(db: Db, actor: Actor, issueId: string) {
  const row = await issueRepo.findById(db, actor.workspaceId, issueId);
  if (!row) throw notFound('Issue not found in your campus.');
  const history = await issueRepo.statusHistory(db, actor.workspaceId, issueId);
  return { issue: toIssueDto(row), history, linkedReports: await reportRepo.listForIssue(db, actor.workspaceId, issueId) };
}

export async function listIssues(
  db: Db,
  actor: Actor,
  filters: {
    status?: string | undefined;
    blockId?: string | undefined;
    categoryId?: string | undefined;
    claimedByUserId?: string | undefined;
    overdueOnly?: boolean | undefined;
    severity?: string | undefined;
    anyReportAiSeverity?: string | undefined;
    createdAfter?: string | undefined;
    createdBefore?: string | undefined;
    limit: number;
    offset: number;
  },
) {
  if (actor.role === 'STUDENT') {
    // Students see their OWN reports, never the operational queue.
    throw forbidden('Students cannot browse the campus issue queue.');
  }
  const { items, total } = await issueRepo.paginate(db, actor.workspaceId, filters);
  return { items: items.map((row) => toIssueDto(row)), total };
}

/**
 * Evidence authorization. The brief requires private photos: a student may read
 * only their own report's photo; HOD/ADMIN may read photos in their own workspace.
 * Enforced server-side on every read — the storage key is never exposed publicly.
 */
export function canReadEvidence(actor: Actor, report: { reporter_user_id: string }): boolean {
  if (actor.role === 'HOD' || actor.role === 'ADMIN') return true;
  return report.reporter_user_id === actor.userId;
}

/**
 * Asserts the actor's session workspace matches the workspace being acted upon.
 * Defence in depth alongside session-derived scoping: if a request ever carries an
 * explicit workspace (e.g. an admin tool), a DEMO session cannot reach REAL data.
 */
export function assertSameWorkspace(sessionWorkspaceId: string, targetWorkspaceId: string): void {
  if (sessionWorkspaceId !== targetWorkspaceId) throw workspaceViolation();
}

